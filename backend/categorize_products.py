FALLBACK_CATEGORY_ID = "1bf4ad45-73af-41b1-82df-6d44177b5bf0"


def normalize_title(title: str) -> str:
    title = title.lower()
    title = re.sub(r'[^a-zа-яіїєґ0-9\s]', ' ', title)
    title = re.sub(r'\s+', ' ', title).strip()
    return title


def find_category(title: str) -> str | None:
    normalized = normalize_title(title)
    words = normalized.split()
    
    for length in range(min(5, len(words)), 0, -1):
        for i in range(len(words) - length + 1):
            phrase = ' '.join(words[i:i+length])
            if phrase in KEYWORD_TO_CATEGORY:
                return KEYWORD_TO_CATEGORY[phrase][0]
    
    for word in words:
        if word in KEYWORD_TO_CATEGORY:
            return KEYWORD_TO_CATEGORY[word][0]
    
    return None


async def categorize_products():
    engine = create_async_engine(settings.DATABASE_URL)
    async_session = async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
    
    async with async_session() as session:
        try:
            result = await session.execute(
                text("SELECT id, title FROM products WHERE category_id IS NULL ORDER BY title")
            )
            products = result.fetchall()
            total = len(products)
            print(f"📦 Знайдено товарів без категорії: {total}")
            
            categorized = 0
            not_found = 0
            
            for product_id, title in products:
                cat_id = find_category(title)
                if cat_id:
                    await session.execute(
                        text("UPDATE products SET category_id = :cat_id WHERE id = :pid"),
                        {"cat_id": cat_id, "pid": product_id}
                    )
                    categorized += 1
                else:
                    await session.execute(
                        text("UPDATE products SET category_id = :cat_id WHERE id = :pid"),
                        {"cat_id": FALLBACK_CATEGORY_ID, "pid": product_id}
                    )
                    not_found += 1
                
                if (categorized + not_found) % 500 == 0:
                    print(f"   Оброблено: {categorized + not_found}/{total}")
                    await session.flush()
            
            await session.commit()
            
            print(f"\n📊 РЕЗУЛЬТАТИ КАТЕГОРИЗАЦІЇ")
            print(f"   ✅ Категоризовано: {categorized}")
            print(f"   ⚠️  Без категорії: {not_found}")
            print(f"   📦 Всього: {total}")
            
        except Exception as e:
            await session.rollback()
            print(f"\n❌ ПОМИЛКА: {e}")
            raise
        finally:
            await engine.dispose()


if __name__ == "__main__":
    asyncio.run(categorize_products())
