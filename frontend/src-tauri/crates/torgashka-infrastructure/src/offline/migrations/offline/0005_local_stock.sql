-- 0005_local_stock.sql
-- ЕТАП 6 (offline-first): локальний stock — робоче сховище кількостей каси
-- (sync-schema-design.md, розділ 8.1: «локальний stock»).
--
-- Призначення:
--   * каса веде власні залишки НЕЗАЛЕЖНО від сервера (операції працюють
--     з вимкненим сервером);
--   * stock-ефекти транзакцій (продаж −, повернення +, закупка +, списання −,
--     інвентаризація = факт) застосовуються АТОМАРНО з записом агрегата
--     (дизайн 4.4) — у тій самій SQLite-транзакції;
--   * quantity зберігається в МІЛІОДИНИЦЯХ (ціле, scale 3) — як серверний
--     parse_scaled3: 1 шт = 1000, 0.500 кг = 500. Цілочисельна арифметика
--     без похибок f64 (0.1+0.2 ≠ 0.3).
--
-- Примітка (обмеження pull): серверний master-pull (ЕТАП 3) віддає лише
-- довідники (categories/products/...); сутності «stock» (поточні кількості
-- точки) у дельті НЕМАЄ. Тому локальний stock стартує порожнім і наповнюється
-- касами: перша інвентаризація фіксує фактичні залишки (set_level), далі —
-- дельти операцій. До першої інвентаризації продаж НЕ блокується відсутністю
-- рядка (level = 0) — залишок може йти в мінус (тимчасово неточний), UI
-- показує фактичний локальний стан.

CREATE TABLE IF NOT EXISTS stock (
    store_id   TEXT NOT NULL,
    product_id TEXT NOT NULL,
    quantity   INTEGER NOT NULL DEFAULT 0,   -- міліодиниці (scale 3)
    updated_at TEXT NOT NULL DEFAULT (datetime('now')),
    PRIMARY KEY (store_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_stock_product ON stock(product_id);
